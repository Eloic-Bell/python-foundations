x = int(input("what is x?"))
y = int(input("what is y?"))

# if statement to compare the values of x and y
if x > y:
    print("x is greater than y")
#elif statement to compare the values of x and y
elif x<y:
    print("x is less than y")
#else statement allows for the program to run if the if and elif statements are not true
else:
    print("x is equal to y")

